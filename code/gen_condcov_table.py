"""Generate the conditional-coverage LaTeX table from conditional_coverage.xlsx.

Usage:
    python gen_condcov_table.py
    python gen_condcov_table.py --level 50
"""

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from config import PROJECT_ROOT, VOLARE_RESULTS_DIR
from gen_density_table import HAR, MODELS

# (method, column, header, format)
COLUMNS = [
    ("raw_cqr_window", "coverage", "Raw", "{:.2f}"),
    ("cqr", "coverage", "CQR", "{:.2f}"),
    ("cqr", "cov_calm", "Calm", "{:.2f}"),
    ("cqr", "cov_normal", "Normal", "{:.2f}"),
    ("cqr", "cov_turbulent", "Turb.", "{:.2f}"),
    ("cqr", "reject_ind_pct", "Ind", "{:.0f}"),
    ("cqr", "reject_dq_pct", "DQ", "{:.0f}"),
]


def build(summary: pd.DataFrame, level: int) -> str:
    sub = summary[summary["level"] == level].set_index(["model", "horizon", "method"])
    models = [m for m in MODELS if m in sub.index.get_level_values("model")]
    ncol = len(COLUMNS) + 1
    head = ("Model & \\multicolumn{2}{c}{Coverage} & \\multicolumn{3}{c}{CQR coverage by state}"
            " & \\multicolumn{2}{c}{CQR reject (\\%)} \\\\\n"
            "\\cmidrule(lr){2-3}\\cmidrule(lr){4-6}\\cmidrule(lr){7-8}\n"
            + " & ".join([""] + [c[2] for c in COLUMNS]) + " \\\\")
    panels = []
    for h, letter in ((1, "A"), (5, "B"), (22, "C")):
        lines = [f"\\multicolumn{{{ncol}}}{{l}}{{\\textbf{{Panel {letter}: $h = {h}$}}}} \\\\"]
        prev_har = None
        for m in models:
            if prev_har and m not in HAR:
                lines.append("\\addlinespace")
            prev_har = m in HAR
            cells = [MODELS[m]] + [fmt.format(sub.at[(m, h, meth), col]) for meth, col, _, fmt in COLUMNS]
            lines.append(" & ".join(cells) + " \\\\")
        panels.append("\n".join(lines))
    body = "\n\\midrule\n".join(panels)
    return f"""% Generated by code/gen_condcov_table.py -- do not edit by hand.
% Requires \\usepackage{{booktabs, threeparttable}}
\\begin{{table}}[htbp]
\\centering
\\begin{{threeparttable}}
\\caption{{Conditional coverage of {level}\\% intervals before and after split-conformal recalibration: means over the 40 stocks.}}
\\label{{tab:cond-cov}}
\\footnotesize
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{l{"c" * len(COLUMNS)}}}
\\toprule
{head}
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\begin{{tablenotes}}\\footnotesize
\\item All columns use the dates covered by the conformal test blocks. Raw and CQR are the empirical coverage of the model's own interval and of its CQR-recalibrated interval (nominal {level / 100:.2f}).
\\item Calm, Normal and Turb.\\ split each stock's dates into terciles of the mean realized variance over the 22 days before the forecast origin, which is known when the forecast is made.
\\item Ind and DQ are rejection rates (\\%) at the 5\\% level across the 40 stocks for the CQR intervals: the Christoffersen (1998) independence test, and the dynamic-quantile regression of misses on a lagged miss and the volatility state (Engle and Manganelli, 2004) with a Monte Carlo p-value. At $h > 1$ both use every $h$-th forecast origin.
\\end{{tablenotes}}
\\end{{threeparttable}}
\\end{{table}}
"""


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--input", default=str(VOLARE_RESULTS_DIR / "density" / "conditional_coverage.xlsx"))
    p.add_argument("--output", default=str(PROJECT_ROOT / "paper" / "tables" / "table_conditional_coverage.tex"))
    p.add_argument("--level", type=int, default=80)
    args = p.parse_args()
    summary = pd.read_excel(args.input, sheet_name="summary")
    Path(args.output).write_text(build(summary, args.level))
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
